def test_parse_rows_totals_and_glued_names():
    r = parse(TEXT)
    assert r["problems"] == []
    assert [(x["customer"], x["product"], x["qty"], x["amount"]) for x in r["rows"]] == [
        ("เซฟ", "ซอง", 5.0, 700.0), ("บริษัท บิกซี ซูเปอร์เซ็นเตอร์ จำกัด (มหาชน)", "ซอง", 11.0, 1540.0),
        ("CPF ซิลเลอร์", "หลอดใหญ่", 1056.0, 71851.5)]
    assert r["rows"][2]["weight"] == 159670.0 and r["rows"][2]["date"] == "2026-01-02"
    assert [d["amount"] for d in r["days"]] == [2240.0, 71851.5]


def test_a_misread_day_is_reported():
    r = parse(TEXT.replace(" 2,240.00\nผลรวม", " 2,300.00\nผลรวม", 1))
    assert any("vs total" in p for p in r["problems"])
